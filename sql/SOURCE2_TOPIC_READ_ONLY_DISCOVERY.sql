-- 3) Identity and CURATED_JSON completeness.
SELECT
    COUNT(*) AS RAW_ROWS,
    COUNT_IF(CONTENT_ID IS NULL OR TRIM(CONTENT_ID::STRING) = '') AS MISSING_CONTENT_ID_ROWS,
    COUNT(DISTINCT CONTENT_ID::STRING) AS DISTINCT_CONTENT_IDS,
    COUNT_IF(CURATED_JSON IS NULL) AS NULL_CURATED_JSON_ROWS,
    COUNT_IF(TYPEOF(CURATED_JSON) <> 'OBJECT') AS NON_OBJECT_CURATED_JSON_ROWS
FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW;

-- 4) Full top-level CURATED_JSON key inventory: names, population and observed JSON types.
WITH key_rows AS (
    SELECT
        f.VALUE::STRING AS FIELD_NAME,
        GET(t.CURATED_JSON, f.VALUE::STRING) AS FIELD_VALUE
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW t,
         LATERAL FLATTEN(INPUT => OBJECT_KEYS(t.CURATED_JSON)) f
)
SELECT
    FIELD_NAME,
    COUNT(*) AS ROWS_WITH_KEY,
    COUNT_IF(FIELD_VALUE IS NOT NULL AND NOT IS_NULL_VALUE(FIELD_VALUE)) AS POPULATED_ROWS,
    COUNT_IF(IS_NULL_VALUE(FIELD_VALUE)) AS JSON_NULL_ROWS,
    LISTAGG(DISTINCT TYPEOF(FIELD_VALUE), ', ') WITHIN GROUP (ORDER BY TYPEOF(FIELD_VALUE)) AS OBSERVED_TYPES
FROM key_rows
GROUP BY FIELD_NAME
ORDER BY FIELD_NAME;

