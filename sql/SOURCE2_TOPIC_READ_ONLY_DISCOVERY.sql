-- 7) Parent Source reference cardinality and exact join coverage.
WITH topic_parent_refs AS (
    SELECT
        t.CONTENT_ID::STRING AS TOPIC_CONTENT_ID,
        r.VALUE AS REF_ITEM,
        TRY_TO_VARCHAR(r.VALUE:ContentId) AS SOURCE_CONTENT_ID
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW t,
         LATERAL FLATTEN(INPUT => GET(t.CURATED_JSON, 'SOURCE_REFERENCES'), OUTER => TRUE) r
), per_topic AS (
    SELECT
        TOPIC_CONTENT_ID,
        COUNT_IF(REF_ITEM IS NOT NULL) AS REF_COUNT
    FROM topic_parent_refs
    GROUP BY TOPIC_CONTENT_ID
), joined AS (
    SELECT
        r.TOPIC_CONTENT_ID,
        r.SOURCE_CONTENT_ID,
        s.CONTENT_ID::STRING AS MATCHED_SOURCE_CONTENT_ID
    FROM topic_parent_refs r
    LEFT JOIN RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW s
      ON s.CONTENT_ID::STRING = r.SOURCE_CONTENT_ID
    WHERE r.REF_ITEM IS NOT NULL
)
SELECT
    (SELECT COUNT(*) FROM per_topic) AS TOPIC_ROWS,
    (SELECT COUNT_IF(REF_COUNT = 0) FROM per_topic) AS TOPICS_WITH_NO_SOURCE_REFERENCE,
    (SELECT COUNT_IF(REF_COUNT = 1) FROM per_topic) AS TOPICS_WITH_ONE_SOURCE_REFERENCE,
    (SELECT COUNT_IF(REF_COUNT > 1) FROM per_topic) AS TOPICS_WITH_MULTIPLE_SOURCE_REFERENCES,
    COUNT(*) AS SOURCE_REFERENCE_ITEMS,
    COUNT_IF(SOURCE_CONTENT_ID IS NULL OR TRIM(SOURCE_CONTENT_ID) = '') AS SOURCE_REFERENCE_ITEMS_WITHOUT_CONTENT_ID,
    COUNT_IF(MATCHED_SOURCE_CONTENT_ID IS NULL) AS UNMATCHED_SOURCE_REFERENCE_ITEMS,
    COUNT(DISTINCT MATCHED_SOURCE_CONTENT_ID) AS DISTINCT_MATCHED_SOURCE_RECORDS
FROM joined;

-- 8) Reference item shapes only; no actual IDs/values returned.
WITH refs AS (
    SELECT 'SOURCE_REFERENCES' AS FIELD_NAME, r.VALUE AS ITEM
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW t,
         LATERAL FLATTEN(INPUT => GET(t.CURATED_JSON, 'SOURCE_REFERENCES')) r
    UNION ALL
    SELECT 'SECTION_REFERENCES', r.VALUE
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW t,
         LATERAL FLATTEN(INPUT => GET(t.CURATED_JSON, 'SECTION_REFERENCES')) r
    UNION ALL
    SELECT 'CONTROL_STANDARDS', r.VALUE
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW t,
         LATERAL FLATTEN(INPUT => GET(t.CURATED_JSON, 'CONTROL_STANDARDS')) r
), item_keys AS (
    SELECT
        FIELD_NAME,
        TYPEOF(ITEM) AS ITEM_TYPE,
        k.VALUE::STRING AS ITEM_KEY
    FROM refs,
         LATERAL FLATTEN(INPUT => IFF(TYPEOF(ITEM) = 'OBJECT', OBJECT_KEYS(ITEM), ARRAY_CONSTRUCT())) k
)
SELECT
    FIELD_NAME,
    ITEM_TYPE,
    COUNT(*) AS KEY_OCCURRENCES,
    LISTAGG(DISTINCT ITEM_KEY, ', ') WITHIN GROUP (ORDER BY ITEM_KEY) AS OBSERVED_ITEM_KEYS
FROM item_keys
GROUP BY FIELD_NAME, ITEM_TYPE
ORDER BY FIELD_NAME, ITEM_TYPE;

-- 9) Value-list/security-object shape summary for fields likely to require transforms.
WITH fields(FIELD_NAME) AS (
    SELECT COLUMN1 FROM VALUES
        ('CONTENT_SOURCE'),
        ('CRITICALITY'),
        ('COMPLIANCE_RATING'),
        ('ENGAGEMENT_SCOPE_IN_CONTROL_TOPIC'),
        ('DEFAULT_RECORD_PERMISSIONS')
), values_by_field AS (
    SELECT
        f.FIELD_NAME,
        GET(t.CURATED_JSON, f.FIELD_NAME) AS FIELD_VALUE
    FROM fields f
    CROSS JOIN RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW t
    WHERE GET(t.CURATED_JSON, f.FIELD_NAME) IS NOT NULL
      AND NOT IS_NULL_VALUE(GET(t.CURATED_JSON, f.FIELD_NAME))
), object_keys AS (
    SELECT
        FIELD_NAME,
        TYPEOF(FIELD_VALUE) AS VALUE_TYPE,
        k.VALUE::STRING AS OBJECT_KEY
    FROM values_by_field,
         LATERAL FLATTEN(INPUT => IFF(TYPEOF(FIELD_VALUE) = 'OBJECT', OBJECT_KEYS(FIELD_VALUE), ARRAY_CONSTRUCT())) k
)
SELECT
    FIELD_NAME,
    VALUE_TYPE,
    COUNT(*) AS KEY_OCCURRENCES,
    LISTAGG(DISTINCT OBJECT_KEY, ', ') WITHIN GROUP (ORDER BY OBJECT_KEY) AS OBSERVED_OBJECT_KEYS
FROM object_keys
GROUP BY FIELD_NAME, VALUE_TYPE
ORDER BY FIELD_NAME, VALUE_TYPE;

