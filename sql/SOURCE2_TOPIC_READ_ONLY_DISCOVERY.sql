-- 1) Verify the physical Topic table name first.
SELECT
    TABLE_CATALOG,
    TABLE_SCHEMA,
    TABLE_NAME,
    ROW_COUNT,
    CREATED,
    LAST_ALTERED
FROM RTX_RAW_DEV.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA = 'ES_ESC_GRC'
  AND UPPER(TABLE_NAME) LIKE '%AUTHORITATIVE%SOURCES%TOPIC%'
ORDER BY TABLE_NAME;

-- Expected candidate from the owner-supplied logical Archer name + established RAW naming pattern:
