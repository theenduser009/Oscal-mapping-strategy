SELECT
    S.SOURCE_RECORD_ID AS ARCHER_AUTHORIZATION_PACKAGE_DATA_CONTENT_ID,

    -- SSP native values
    SC.AUTHORIZATION_PACKAGE_NAME,
    SC.ACRONYM,
    IDS.SAP_ID,
    SC.MISSION_PURPOSE,
    SC.OPERATIONAL_STATUS,
    SC.AUTHORIZATION_COMMENTS,
    SC.ATOIATO_DATE,
    SC.SECURITY_CATEGORY,
    AB.AUTHORIZATION_BOUNDARY_DESCRIPTION,
    SI.SECURITY_OBJECTIVE_CONFIDENTIALITY,
    SI.SECURITY_OBJECTIVE_INTEGRITY,
    SI.SECURITY_OBJECTIVE_AVAILABILITY,

    -- Metadata
    MD.OSCAL_METADATA_TITLE,
    MD.OSCAL_DOCUMENT_VERSION,
    MD.OSCAL_VERSION,
    MD.PUBLISHED,
    MD.LAST_MODIFIED,
    DI.TRACKING_ID,
    DI.DOCUMENT_IDS,
    MP.SSP_METADATA_PROPERTIES,

    -- Existing easy-to-consume SSP property columns
    P.SSP_SYSTEM_CHARACTERISTICS_PROPERTIES:"information-system-type"[0]::STRING AS INFORMATION_SYSTEM_TYPE,
    P.SSP_SYSTEM_CHARACTERISTICS_PROPERTIES:"fisma-reportable"[0]::STRING AS FISMA_REPORTABLE,
    P.SSP_SYSTEM_CHARACTERISTICS_PROPERTIES:"financial-system"[0]::STRING AS FINANCIAL_SYSTEM,
    P.SSP_SYSTEM_CHARACTERISTICS_PROPERTIES:"mission-critical"[0]::STRING AS MISSION_CRITICAL,
    P.SSP_SYSTEM_CHARACTERISTICS_PROPERTIES:"critical-infrastructure"[0]::STRING AS CRITICAL_INFRASTRUCTURE,
    P.SSP_SYSTEM_CHARACTERISTICS_PROPERTIES:"package-type"[0]::STRING AS PACKAGE_TYPE,
    P.SSP_SYSTEM_CHARACTERISTICS_PROPERTIES:"pia-required"[0]::STRING AS PIA_REQUIRED,
    P.SSP_SYSTEM_CHARACTERISTICS_PROPERTIES:"information-classification"[0]::STRING AS INFORMATION_CLASSIFICATION,
    P.SSP_SYSTEM_CHARACTERISTICS_PROPERTIES:"daily-loss-amount-from-outage"[0]::STRING AS DAILY_LOSS_AMOUNT_FROM_OUTAGE,
    P.SSP_SYSTEM_CHARACTERISTICS_PROPERTIES:"authorization-decision"[0]::STRING AS AUTHORIZATION_DECISION,

    -- All system-characteristics properties, including Control Implementation
    -- summary/source-preservation properties, in one future-friendly object.
    P.SSP_SYSTEM_CHARACTERISTICS_PROPERTIES,

    -- SSP people and structural collections
    RP.INFORMATION_OWNER_IO_PARTY_UUIDS,
    RP.INFORMATION_SYSTEM_OWNER_ISO_PARTY_UUIDS,
    RP.SISSO_PARTY_UUIDS,
    RP.AUTHORIZING_OFFICIAL_AO_PARTY_UUIDS,
    RP.INFORMATION_SYSTEM_SECURITY_OFFICER_ISSO_PARTY_UUIDS,
    RP.ISSE_PARTY_UUIDS,
    RP.ISA_PARTY_UUIDS,
    RP.AODR_PARTY_UUIDS,
    RP.PRIVACY_OFFICER_PO_PARTY_UUIDS,
    RP.RESPONSIBLE_PARTIES,
    RL.ROLES,
    PT.PARTIES,
    IDS.SYSTEM_IDS,

    -- SSP System Implementation + Control Implementation
    COALESCE(CP.COMPONENT_COUNT,0) AS COMPONENT_COUNT,
    CP.COMPONENTS,
    COALESCE(IR.IMPLEMENTED_REQUIREMENT_COUNT,0) AS IMPLEMENTED_REQUIREMENT_COUNT,
    IR.IMPLEMENTED_REQUIREMENTS,

    -- SSP identity / QA
    S.SSP_ROOT_PK,
    S.SSP_UUID,
    NS.SSP_NODE_COUNT,
    ES.SSP_EDGE_COUNT,
    NS.SSP_PROP_NODE_COUNT,
    IFF(NS.SSP_ROOT_COUNT=1
        AND COALESCE(ES.SSP_EDGE_COUNT,0)=NS.SSP_NODE_COUNT-1
        AND COALESCE(ES.SSP_CROSS_RECORD_EDGE_COUNT,0)=0,
        'PASS','FAIL') AS SSP_RELATIONSHIP_INTEGRITY,

    -- Assessment Results
    AR.ASSESSMENT_RESULTS_ROOT_PK,
    AR.ASSESSMENT_RESULTS_UUID,
    ANS.AR_NODE_COUNT,
    AES.AR_EDGE_COUNT,
    ANS.AR_OBSERVATION_COUNT,
    ANS.AR_NATIVE_FINDING_COUNT,
    ANS.AR_PROP_NODE_COUNT,
    AO.ASSESSMENT_OBSERVATIONS,
    APROP.ASSESSMENT_RESULT_PROPERTIES,
    IFF(ANS.AR_ROOT_COUNT=1
        AND COALESCE(AES.AR_EDGE_COUNT,0)=ANS.AR_NODE_COUNT-1
        AND COALESCE(AES.AR_CROSS_RECORD_EDGE_COUNT,0)=0,
        'PASS','FAIL') AS ASSESSMENT_RESULTS_RELATIONSHIP_INTEGRITY,

    -- POA&M
    PR.POAM_ROOT_PK,
    PR.POAM_UUID,
    PNS.POAM_NODE_COUNT,
    PES.POAM_EDGE_COUNT,
    COALESCE(PI.POAM_ITEM_COUNT,0) AS POAM_ITEM_COUNT,
    PI.POAM_ITEMS,
    IFF(PNS.POAM_ROOT_COUNT=1
        AND COALESCE(PES.POAM_EDGE_COUNT,0)=PNS.POAM_NODE_COUNT-1
        AND COALESCE(PES.POAM_CROSS_RECORD_EDGE_COUNT,0)=0,
        'PASS','FAIL') AS POAM_RELATIONSHIP_INTEGRITY,

    -- Security Assessment Plan
    SAP.ASSESSMENT_PLAN_ROOT_PK,
    SAP.ASSESSMENT_PLAN_UUID,
    SNS.SAP_NODE_COUNT,
    SES.SAP_EDGE_COUNT,
    SNS.SAP_TASK_COUNT,
    SNS.SAP_PROP_NODE_COUNT,
    ST.ASSESSMENT_TASKS,
    SPROP.ASSESSMENT_PLAN_PROPERTIES,
    IFF(SNS.SAP_ROOT_COUNT=1
        AND COALESCE(SES.SAP_EDGE_COUNT,0)=SNS.SAP_NODE_COUNT-1
        AND COALESCE(SES.SAP_CROSS_RECORD_EDGE_COUNT,0)=0,
        'PASS','FAIL') AS ASSESSMENT_PLAN_RELATIONSHIP_INTEGRITY,

    -- Cross-model QA
    IFF(AR.SOURCE_RECORD_ID IS NOT NULL,1,0) AS HAS_ASSESSMENT_RESULTS,
    IFF(PR.SOURCE_RECORD_ID IS NOT NULL,1,0) AS HAS_POAM,
    IFF(SAP.SOURCE_RECORD_ID IS NOT NULL,1,0) AS HAS_ASSESSMENT_PLAN,
    IFF(
        AR.SOURCE_RECORD_ID IS NOT NULL
        AND PR.SOURCE_RECORD_ID IS NOT NULL
        AND SAP.SOURCE_RECORD_ID IS NOT NULL,
        'PASS','FAIL'
    ) AS CROSS_MODEL_COVERAGE,

    IFF(
        NS.SSP_ROOT_COUNT=1
        AND COALESCE(ES.SSP_EDGE_COUNT,0)=NS.SSP_NODE_COUNT-1
        AND COALESCE(ES.SSP_CROSS_RECORD_EDGE_COUNT,0)=0
        AND ANS.AR_ROOT_COUNT=1
        AND COALESCE(AES.AR_EDGE_COUNT,0)=ANS.AR_NODE_COUNT-1
        AND COALESCE(AES.AR_CROSS_RECORD_EDGE_COUNT,0)=0
        AND PNS.POAM_ROOT_COUNT=1
        AND COALESCE(PES.POAM_EDGE_COUNT,0)=PNS.POAM_NODE_COUNT-1
        AND COALESCE(PES.POAM_CROSS_RECORD_EDGE_COUNT,0)=0
        AND SNS.SAP_ROOT_COUNT=1
        AND COALESCE(SES.SAP_EDGE_COUNT,0)=SNS.SAP_NODE_COUNT-1
        AND COALESCE(SES.SAP_CROSS_RECORD_EDGE_COUNT,0)=0,
        'PASS','FAIL'
    ) AS OVERALL_RELATIONSHIP_INTEGRITY

FROM SSP_ROOT S
LEFT JOIN SSP_SYSTEM_CHARACTERISTICS SC
  ON SC.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID
LEFT JOIN SSP_SYSTEM_IDS IDS
  ON IDS.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID
LEFT JOIN SSP_AUTHORIZATION_BOUNDARY AB
  ON AB.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID
LEFT JOIN SSP_SECURITY_IMPACT SI
  ON SI.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID
LEFT JOIN SSP_SC_PROPERTIES P
  ON P.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID
LEFT JOIN SSP_METADATA MD
  ON MD.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID
LEFT JOIN SSP_DOCUMENT_IDS DI
  ON DI.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID
LEFT JOIN SSP_METADATA_PROPERTIES MP
  ON MP.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID
LEFT JOIN SSP_RESPONSIBLE_PARTIES RP
  ON RP.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID
LEFT JOIN SSP_ROLES RL
  ON RL.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID
LEFT JOIN SSP_PARTIES PT
  ON PT.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID
LEFT JOIN SSP_COMPONENTS CP
  ON CP.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID
LEFT JOIN SSP_IMPLEMENTED_REQUIREMENTS IR
  ON IR.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID
LEFT JOIN SSP_NODE_STATS NS
  ON NS.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID
LEFT JOIN SSP_EDGE_STATS ES
  ON ES.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID

LEFT JOIN AR_ROOT AR
  ON AR.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID
LEFT JOIN AR_NODE_STATS ANS
  ON ANS.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID
LEFT JOIN AR_EDGE_STATS AES
  ON AES.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID
LEFT JOIN AR_OBSERVATIONS AO
  ON AO.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID
LEFT JOIN AR_PROPERTIES APROP
  ON APROP.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID

LEFT JOIN POAM_ROOT PR
  ON PR.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID
LEFT JOIN POAM_NODE_STATS PNS
  ON PNS.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID
LEFT JOIN POAM_EDGE_STATS PES
  ON PES.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID
LEFT JOIN POAM_ITEMS PI
  ON PI.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID

LEFT JOIN SAP_ROOT SAP
  ON SAP.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID
LEFT JOIN SAP_NODE_STATS SNS
  ON SNS.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID
LEFT JOIN SAP_EDGE_STATS SES
  ON SES.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID
LEFT JOIN SAP_TASKS ST
  ON ST.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID
LEFT JOIN SAP_PROPERTIES SPROP
  ON SPROP.SOURCE_RECORD_ID = S.SOURCE_RECORD_ID;
