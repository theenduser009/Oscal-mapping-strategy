            )
        ) WITHIN GROUP (ORDER BY OSCAL_UUID) AS ASSESSMENT_OBSERVATIONS
    FROM AR_NODES
    WHERE ELEMENT_TYPE = 'observations'
    GROUP BY SOURCE_RECORD_ID
),

AR_PROP_VALUES AS
(
    SELECT
        SOURCE_RECORD_ID,
        METADATA_JSON:"name"::STRING AS PROP_NAME,
        ARRAY_AGG(METADATA_JSON:"value")
          WITHIN GROUP (ORDER BY OSCAL_UUID) AS PROP_VALUES
    FROM AR_NODES
    WHERE ELEMENT_TYPE = 'props'
      AND METADATA_JSON:"name" IS NOT NULL
    GROUP BY SOURCE_RECORD_ID, METADATA_JSON:"name"::STRING
),

AR_PROPERTIES AS
(
    SELECT
        SOURCE_RECORD_ID,
        OBJECT_AGG(PROP_NAME, TO_VARIANT(PROP_VALUES)) AS ASSESSMENT_RESULT_PROPERTIES
    FROM AR_PROP_VALUES
    GROUP BY SOURCE_RECORD_ID
),

