-- Expanded published OSCAL Authorization Package view.
-- Date: 2026-09-25
--
-- One row per Source One Authorization Package / SOURCE_RECORD_ID.
-- Uses only committed OSCAL DIM/FACT tables.
--
-- Design rules:
-- * SOURCE_RECORD_ID is the cross-model business key.
-- * FACT foreign keys validate hierarchy within each OSCAL model.
-- * Every one-to-many collection is aggregated before the final cross-model join.
-- * Assessment Results is explicitly scoped to Source One because its DIM/FACT
--   tables are shared with Source Two.
-- * This view exposes native scalar fields for easy consumers and also exposes
--   structured VARIANT arrays/objects for components, controls, observations,
--   POA&M items, tasks, parties, and extension properties.
-- * No RAW/historical table dependency.
--
-- Recreate C2S_OSCAL_AUTHORIZATION_PACKAGE_ACTIVE after this view so SELECT *
-- picks up the expanded column set.

CREATE OR REPLACE VIEW
RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_PUBLISHED.C2S_OSCAL_AUTHORIZATION_PACKAGE_ALL
AS

WITH
-- =====================================================================
-- SSP
-- =====================================================================
SSP_NODES AS
(
    SELECT
        PK_OSCAL_SSP_ELEMENT_HASH AS NODE_KEY,
        SOURCE_RECORD_ID,
        ELEMENT_TYPE,
        OSCAL_UUID,
        METADATA_JSON
    FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT
    WHERE SOURCE_SYSTEM_NAME = 'ARCHER'
      AND SOURCE_TABLE_NAME = 'ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
),

SSP_ROOT AS
(
    SELECT
        SOURCE_RECORD_ID,
        NODE_KEY AS SSP_ROOT_PK,
        OSCAL_UUID AS SSP_UUID
    FROM SSP_NODES
    WHERE ELEMENT_TYPE = 'system-security-plan'
),

SSP_EDGE_STATS AS
(
    SELECT
        S.SOURCE_RECORD_ID,
        COUNT(*) AS SSP_EDGE_COUNT,
        COUNT_IF(S.SOURCE_RECORD_ID <> T.SOURCE_RECORD_ID) AS SSP_CROSS_RECORD_EDGE_COUNT
    FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_SSP_DEPENDENCY F
    JOIN SSP_NODES S
      ON S.NODE_KEY = F.FK_SOURCE_ELEMENT_HASH
    JOIN SSP_NODES T
      ON T.NODE_KEY = F.FK_TARGET_ELEMENT_HASH
    GROUP BY S.SOURCE_RECORD_ID
),

SSP_NODE_STATS AS
(
    SELECT
        SOURCE_RECORD_ID,
        COUNT(*) AS SSP_NODE_COUNT,
        COUNT_IF(ELEMENT_TYPE = 'system-security-plan') AS SSP_ROOT_COUNT,
        COUNT_IF(ELEMENT_TYPE = 'metadata') AS SSP_METADATA_NODE_COUNT,
        COUNT_IF(ELEMENT_TYPE = 'system-characteristics') AS SSP_SYSTEM_CHARACTERISTICS_NODE_COUNT,
        COUNT_IF(ELEMENT_TYPE = 'components') AS SSP_COMPONENT_NODE_COUNT,
        COUNT_IF(ELEMENT_TYPE = 'implemented-requirements') AS SSP_IMPLEMENTED_REQUIREMENT_COUNT,
        COUNT_IF(ELEMENT_TYPE = 'props') AS SSP_PROP_NODE_COUNT
    FROM SSP_NODES
    GROUP BY SOURCE_RECORD_ID
),

SSP_ROOT_CHILDREN AS
(
    SELECT
        R.SOURCE_RECORD_ID,
        C.NODE_KEY,
        C.ELEMENT_TYPE,
        C.OSCAL_UUID,
        C.METADATA_JSON
    FROM SSP_ROOT R
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_SSP_DEPENDENCY F
      ON F.FK_SOURCE_ELEMENT_HASH = R.SSP_ROOT_PK
    JOIN SSP_NODES C
      ON C.NODE_KEY = F.FK_TARGET_ELEMENT_HASH
),

SSP_SYSTEM_CHARACTERISTICS AS
(
    SELECT
        SOURCE_RECORD_ID,
        NODE_KEY AS SYSTEM_CHARACTERISTICS_PK,
        METADATA_JSON:"system-name"::STRING AS AUTHORIZATION_PACKAGE_NAME,
        METADATA_JSON:"system-name-short"::STRING AS ACRONYM,
        METADATA_JSON:"description"::STRING AS MISSION_PURPOSE,
        METADATA_JSON:"status":"state"::STRING AS OPERATIONAL_STATUS,
        METADATA_JSON:"status":"remarks"::STRING AS AUTHORIZATION_COMMENTS,
        METADATA_JSON:"date-authorized"::STRING AS ATOIATO_DATE,
        METADATA_JSON:"security-sensitivity-level"::STRING AS SECURITY_CATEGORY
    FROM SSP_ROOT_CHILDREN
    WHERE ELEMENT_TYPE = 'system-characteristics'
),

SSP_SC_CHILDREN AS
(
    SELECT
        SC.SOURCE_RECORD_ID,
        C.NODE_KEY,
        C.ELEMENT_TYPE,
        C.OSCAL_UUID,
        C.METADATA_JSON
    FROM SSP_SYSTEM_CHARACTERISTICS SC
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_SSP_DEPENDENCY F
      ON F.FK_SOURCE_ELEMENT_HASH = SC.SYSTEM_CHARACTERISTICS_PK
    JOIN SSP_NODES C
      ON C.NODE_KEY = F.FK_TARGET_ELEMENT_HASH
),

SSP_SYSTEM_IDS AS
(
    SELECT
        SOURCE_RECORD_ID,
        ARRAY_AGG(
            OBJECT_CONSTRUCT_KEEP_NULL(
                'uuid', OSCAL_UUID,
                'id', METADATA_JSON:"id"
            )
        ) WITHIN GROUP (ORDER BY OSCAL_UUID) AS SYSTEM_IDS,
        MAX(METADATA_JSON:"id"::STRING) AS SAP_ID
    FROM SSP_SC_CHILDREN
    WHERE ELEMENT_TYPE = 'system-ids'
    GROUP BY SOURCE_RECORD_ID
),

SSP_AUTHORIZATION_BOUNDARY AS
(
    SELECT
        SOURCE_RECORD_ID,
        MAX(METADATA_JSON:"description"::STRING) AS AUTHORIZATION_BOUNDARY_DESCRIPTION
    FROM SSP_SC_CHILDREN
    WHERE ELEMENT_TYPE = 'authorization-boundary'
    GROUP BY SOURCE_RECORD_ID
),

SSP_SECURITY_IMPACT AS
(
    SELECT
        SOURCE_RECORD_ID,
        MAX(METADATA_JSON:"security-objective-confidentiality"::STRING) AS SECURITY_OBJECTIVE_CONFIDENTIALITY,
        MAX(METADATA_JSON:"security-objective-integrity"::STRING) AS SECURITY_OBJECTIVE_INTEGRITY,
        MAX(METADATA_JSON:"security-objective-availability"::STRING) AS SECURITY_OBJECTIVE_AVAILABILITY,
        MAX(METADATA_JSON) AS SECURITY_IMPACT_PAYLOAD
    FROM SSP_SC_CHILDREN
    WHERE ELEMENT_TYPE = 'security-impact-level'
    GROUP BY SOURCE_RECORD_ID
),

SSP_SC_PROP_VALUES AS
(
    SELECT
        SOURCE_RECORD_ID,
        METADATA_JSON:"name"::STRING AS PROP_NAME,
        ARRAY_AGG(METADATA_JSON:"value")
          WITHIN GROUP (ORDER BY OSCAL_UUID) AS PROP_VALUES
    FROM SSP_SC_CHILDREN
    WHERE ELEMENT_TYPE = 'props'
      AND METADATA_JSON:"name" IS NOT NULL
    GROUP BY SOURCE_RECORD_ID, METADATA_JSON:"name"::STRING
),

SSP_SC_PROPERTIES AS
(
    SELECT
        SOURCE_RECORD_ID,
        OBJECT_AGG(PROP_NAME, TO_VARIANT(PROP_VALUES)) AS SSP_SYSTEM_CHARACTERISTICS_PROPERTIES
    FROM SSP_SC_PROP_VALUES
    GROUP BY SOURCE_RECORD_ID
),

SSP_METADATA AS
(
    SELECT
        SOURCE_RECORD_ID,
        NODE_KEY AS METADATA_PK,
        METADATA_JSON:"title"::STRING AS OSCAL_METADATA_TITLE,
        METADATA_JSON:"version"::STRING AS OSCAL_DOCUMENT_VERSION,
        METADATA_JSON:"oscal-version"::STRING AS OSCAL_VERSION,
        METADATA_JSON:"published"::STRING AS PUBLISHED,
        METADATA_JSON:"last-modified"::STRING AS LAST_MODIFIED
    FROM SSP_ROOT_CHILDREN
    WHERE ELEMENT_TYPE = 'metadata'
),

SSP_METADATA_CHILDREN AS
(
    SELECT
        M.SOURCE_RECORD_ID,
        C.NODE_KEY,
        C.ELEMENT_TYPE,
        C.OSCAL_UUID,
        C.METADATA_JSON
    FROM SSP_METADATA M
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_SSP_DEPENDENCY F
      ON F.FK_SOURCE_ELEMENT_HASH = M.METADATA_PK
    JOIN SSP_NODES C
      ON C.NODE_KEY = F.FK_TARGET_ELEMENT_HASH
),

SSP_DOCUMENT_IDS AS
(
    SELECT
        SOURCE_RECORD_ID,
        MAX(METADATA_JSON:"identifier"::STRING) AS TRACKING_ID,
        ARRAY_AGG(METADATA_JSON)
          WITHIN GROUP (ORDER BY OSCAL_UUID) AS DOCUMENT_IDS
    FROM SSP_METADATA_CHILDREN
    WHERE ELEMENT_TYPE = 'document-ids'
    GROUP BY SOURCE_RECORD_ID
),

SSP_METADATA_PROP_VALUES AS
(
    SELECT
        SOURCE_RECORD_ID,
        METADATA_JSON:"name"::STRING AS PROP_NAME,
        ARRAY_AGG(METADATA_JSON:"value")
          WITHIN GROUP (ORDER BY OSCAL_UUID) AS PROP_VALUES
    FROM SSP_METADATA_CHILDREN
    WHERE ELEMENT_TYPE = 'props'
      AND METADATA_JSON:"name" IS NOT NULL
    GROUP BY SOURCE_RECORD_ID, METADATA_JSON:"name"::STRING
),

SSP_METADATA_PROPERTIES AS
(
    SELECT
        SOURCE_RECORD_ID,
        OBJECT_AGG(PROP_NAME, TO_VARIANT(PROP_VALUES)) AS SSP_METADATA_PROPERTIES
    FROM SSP_METADATA_PROP_VALUES
    GROUP BY SOURCE_RECORD_ID
),

SSP_RESPONSIBLE_PARTIES AS
(
    SELECT
        SOURCE_RECORD_ID,
        ARRAY_AGG(
            OBJECT_CONSTRUCT_KEEP_NULL(
                'role-id', METADATA_JSON:"role-id",
                'party-uuids', METADATA_JSON:"party-uuids"
            )
        ) WITHIN GROUP (ORDER BY METADATA_JSON:"role-id"::STRING, OSCAL_UUID) AS RESPONSIBLE_PARTIES,
        MAX(IFF(METADATA_JSON:"role-id"::STRING = 'information-owner',
                METADATA_JSON:"party-uuids"::STRING, NULL)) AS INFORMATION_OWNER_IO_PARTY_UUIDS,
        MAX(IFF(METADATA_JSON:"role-id"::STRING = 'system-owner',
                METADATA_JSON:"party-uuids"::STRING, NULL)) AS INFORMATION_SYSTEM_OWNER_ISO_PARTY_UUIDS,
        MAX(IFF(METADATA_JSON:"role-id"::STRING = 'senior-information-systems-security-officer',
                METADATA_JSON:"party-uuids"::STRING, NULL)) AS SISSO_PARTY_UUIDS,
        MAX(IFF(METADATA_JSON:"role-id"::STRING = 'authorizing-official',
                METADATA_JSON:"party-uuids"::STRING, NULL)) AS AUTHORIZING_OFFICIAL_AO_PARTY_UUIDS,
        MAX(IFF(METADATA_JSON:"role-id"::STRING = 'system-security-officer',
                METADATA_JSON:"party-uuids"::STRING, NULL)) AS INFORMATION_SYSTEM_SECURITY_OFFICER_ISSO_PARTY_UUIDS,
        MAX(IFF(METADATA_JSON:"role-id"::STRING = 'information-system-security-engineer',
                METADATA_JSON:"party-uuids"::STRING, NULL)) AS ISSE_PARTY_UUIDS,
        MAX(IFF(METADATA_JSON:"role-id"::STRING = 'information-system-administrator',
                METADATA_JSON:"party-uuids"::STRING, NULL)) AS ISA_PARTY_UUIDS,
        MAX(IFF(METADATA_JSON:"role-id"::STRING = 'authorizing-official-designated-representative',
                METADATA_JSON:"party-uuids"::STRING, NULL)) AS AODR_PARTY_UUIDS,
        MAX(IFF(METADATA_JSON:"role-id"::STRING = 'privacy-officer',
                METADATA_JSON:"party-uuids"::STRING, NULL)) AS PRIVACY_OFFICER_PO_PARTY_UUIDS
    FROM SSP_METADATA_CHILDREN
    WHERE ELEMENT_TYPE = 'responsible-parties'
    GROUP BY SOURCE_RECORD_ID
),

SSP_ROLES AS
(
    SELECT
        SOURCE_RECORD_ID,
        ARRAY_AGG(METADATA_JSON)
          WITHIN GROUP (ORDER BY OSCAL_UUID) AS ROLES
    FROM SSP_METADATA_CHILDREN
    WHERE ELEMENT_TYPE = 'roles'
    GROUP BY SOURCE_RECORD_ID
),

SSP_PARTIES AS
(
    SELECT
        SOURCE_RECORD_ID,
        ARRAY_AGG(
            OBJECT_CONSTRUCT_KEEP_NULL(
                'uuid', OSCAL_UUID,
                'payload', METADATA_JSON
            )
        ) WITHIN GROUP (ORDER BY OSCAL_UUID) AS PARTIES
    FROM SSP_METADATA_CHILDREN
    WHERE ELEMENT_TYPE = 'parties'
    GROUP BY SOURCE_RECORD_ID
),

SSP_SYSTEM_IMPLEMENTATION AS
(
    SELECT
        SOURCE_RECORD_ID,
        NODE_KEY AS SYSTEM_IMPLEMENTATION_PK
    FROM SSP_ROOT_CHILDREN
    WHERE ELEMENT_TYPE = 'system-implementation'
),

SSP_COMPONENTS AS
(
    SELECT
        SI.SOURCE_RECORD_ID,
        COUNT(*) AS COMPONENT_COUNT,
        ARRAY_AGG(
            OBJECT_CONSTRUCT_KEEP_NULL(
                'uuid', C.OSCAL_UUID,
                'type', C.METADATA_JSON:"type",
                'title', C.METADATA_JSON:"title",
                'description', C.METADATA_JSON:"description",
                'payload', C.METADATA_JSON
            )
        ) WITHIN GROUP (ORDER BY C.OSCAL_UUID) AS COMPONENTS
    FROM SSP_SYSTEM_IMPLEMENTATION SI
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_SSP_DEPENDENCY F
      ON F.FK_SOURCE_ELEMENT_HASH = SI.SYSTEM_IMPLEMENTATION_PK
    JOIN SSP_NODES C
      ON C.NODE_KEY = F.FK_TARGET_ELEMENT_HASH
    WHERE C.ELEMENT_TYPE = 'components'
    GROUP BY SI.SOURCE_RECORD_ID
),

SSP_CONTROL_IMPLEMENTATION AS
(
    SELECT
        SOURCE_RECORD_ID,
        NODE_KEY AS CONTROL_IMPLEMENTATION_PK
    FROM SSP_ROOT_CHILDREN
    WHERE ELEMENT_TYPE = 'control-implementation'
),

SSP_IMPLEMENTED_REQUIREMENTS AS
(
    SELECT
        CI.SOURCE_RECORD_ID,
        COUNT(*) AS IMPLEMENTED_REQUIREMENT_COUNT,
        ARRAY_AGG(
            OBJECT_CONSTRUCT_KEEP_NULL(
                'uuid', C.OSCAL_UUID,
                'control-id', C.METADATA_JSON:"control-id",
                'remarks', C.METADATA_JSON:"remarks",
                'payload', C.METADATA_JSON
            )
        ) WITHIN GROUP (ORDER BY C.METADATA_JSON:"control-id"::STRING, C.OSCAL_UUID) AS IMPLEMENTED_REQUIREMENTS
    FROM SSP_CONTROL_IMPLEMENTATION CI
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_SSP_DEPENDENCY F
      ON F.FK_SOURCE_ELEMENT_HASH = CI.CONTROL_IMPLEMENTATION_PK
    JOIN SSP_NODES C
      ON C.NODE_KEY = F.FK_TARGET_ELEMENT_HASH
    WHERE C.ELEMENT_TYPE = 'implemented-requirements'
    GROUP BY CI.SOURCE_RECORD_ID
),

-- =====================================================================
