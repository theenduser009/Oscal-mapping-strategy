      AND SOURCE_TABLE_NAME = 'ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
),

AR_ROOT AS
(
    SELECT
        SOURCE_RECORD_ID,
        NODE_KEY AS ASSESSMENT_RESULTS_ROOT_PK,
        OSCAL_UUID AS ASSESSMENT_RESULTS_UUID
    FROM AR_NODES
    WHERE ELEMENT_TYPE = 'assessment-results'
),

AR_EDGE_STATS AS
