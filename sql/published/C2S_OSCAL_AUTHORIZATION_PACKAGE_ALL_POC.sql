    SELECT
        S.SOURCE_RECORD_ID,
        COUNT(*) AS AR_EDGE_COUNT,
        COUNT_IF(S.SOURCE_RECORD_ID <> T.SOURCE_RECORD_ID) AS AR_CROSS_RECORD_EDGE_COUNT
    FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_ASSESSMENT_RESULTS_DEPENDENCY F
