  MODEL, NODES, ROOTS, EDGES,
  NODES-ROOTS AS EXPECTED_EDGES_FROM_TREE_GRAIN,
  IFF(EDGES=NODES-ROOTS,'PASS','FAIL') AS GRAPH_CARDINALITY_STATUS,
  BASELINE_NODES, BASELINE_EDGES,
  IFF(NODES=BASELINE_NODES AND EDGES=BASELINE_EDGES,'PASS','DRIFT') AS CURRENT_RELEASE_BASELINE_STATUS
FROM counts
ORDER BY MODEL;


-- =====================================================================
-- 02. ROOT COVERAGE BY CONTENT_ID
-- Every Source One CONTENT_ID must have exactly one root in every executable model.
-- Expected: MISSING_ROOTS=0, DUPLICATE_ROOT_IDS=0, EXTRA_ROOT_IDS=0 for every model.
-- =====================================================================
WITH
src AS (
  SELECT DISTINCT TRIM(CONTENT_ID::STRING) CONTENT_ID
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW
),
ssp_r AS (
  SELECT TRIM(SOURCE_RECORD_ID::STRING) CONTENT_ID, COUNT(*) N
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT
  WHERE SOURCE_SYSTEM_NAME='ARCHER'
    AND SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
    AND ELEMENT_TYPE='system-security-plan'
  GROUP BY 1
),
ar_r AS (
  SELECT TRIM(SOURCE_RECORD_ID::STRING) CONTENT_ID, COUNT(*) N
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT
  WHERE SOURCE_SYSTEM_NAME='ARCHER'
    AND SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
    AND ELEMENT_TYPE='assessment-results'
  GROUP BY 1
),
poam_r AS (
  SELECT TRIM(SOURCE_RECORD_ID::STRING) CONTENT_ID, COUNT(*) N
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_POAM_ELEMENT
  WHERE SOURCE_SYSTEM_NAME='ARCHER'
    AND SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
    AND ELEMENT_TYPE='plan-of-action-and-milestones'
  GROUP BY 1
),
sap_r AS (
  SELECT TRIM(SOURCE_RECORD_ID::STRING) CONTENT_ID, COUNT(*) N
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_PLAN_ELEMENT
  WHERE SOURCE_SYSTEM_NAME='ARCHER'
    AND SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
    AND ELEMENT_TYPE='assessment-plan'
  GROUP BY 1
),
summary AS (
  SELECT 'SSP' MODEL,
         COUNT_IF(r.CONTENT_ID IS NULL) MISSING_ROOTS,
         COUNT_IF(COALESCE(r.N,0)>1) DUPLICATE_ROOT_IDS,
         (SELECT COUNT(*) FROM ssp_r r2 LEFT JOIN src s2 USING(CONTENT_ID) WHERE s2.CONTENT_ID IS NULL) EXTRA_ROOT_IDS
  FROM src s LEFT JOIN ssp_r r USING(CONTENT_ID)
  UNION ALL
  SELECT 'ASSESSMENT_RESULTS',
         COUNT_IF(r.CONTENT_ID IS NULL), COUNT_IF(COALESCE(r.N,0)>1),
         (SELECT COUNT(*) FROM ar_r r2 LEFT JOIN src s2 USING(CONTENT_ID) WHERE s2.CONTENT_ID IS NULL)
  FROM src s LEFT JOIN ar_r r USING(CONTENT_ID)
  UNION ALL
  SELECT 'POAM',
         COUNT_IF(r.CONTENT_ID IS NULL), COUNT_IF(COALESCE(r.N,0)>1),
         (SELECT COUNT(*) FROM poam_r r2 LEFT JOIN src s2 USING(CONTENT_ID) WHERE s2.CONTENT_ID IS NULL)
  FROM src s LEFT JOIN poam_r r USING(CONTENT_ID)
  UNION ALL
  SELECT 'SECURITY_ASSESSMENT_PLAN',
         COUNT_IF(r.CONTENT_ID IS NULL), COUNT_IF(COALESCE(r.N,0)>1),
         (SELECT COUNT(*) FROM sap_r r2 LEFT JOIN src s2 USING(CONTENT_ID) WHERE s2.CONTENT_ID IS NULL)
  FROM src s LEFT JOIN sap_r r USING(CONTENT_ID)
)
SELECT *,
       IFF(MISSING_ROOTS=0 AND DUPLICATE_ROOT_IDS=0 AND EXTRA_ROOT_IDS=0,'PASS','FAIL') STATUS
FROM summary
ORDER BY MODEL;


-- 02B. DETAIL ONLY IF ROOT COVERAGE FAILED. Expected: zero rows.
WITH
src AS (
  SELECT DISTINCT TRIM(CONTENT_ID::STRING) CONTENT_ID
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW
),
roots AS (
  SELECT 'SSP' MODEL, TRIM(SOURCE_RECORD_ID::STRING) CONTENT_ID, COUNT(*) N
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT
  WHERE SOURCE_SYSTEM_NAME='ARCHER' AND SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
    AND ELEMENT_TYPE='system-security-plan' GROUP BY 1,2
  UNION ALL
  SELECT 'ASSESSMENT_RESULTS', TRIM(SOURCE_RECORD_ID::STRING), COUNT(*)
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT
  WHERE SOURCE_SYSTEM_NAME='ARCHER' AND SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
    AND ELEMENT_TYPE='assessment-results' GROUP BY 1,2
  UNION ALL
  SELECT 'POAM', TRIM(SOURCE_RECORD_ID::STRING), COUNT(*)
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_POAM_ELEMENT
  WHERE SOURCE_SYSTEM_NAME='ARCHER' AND SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
    AND ELEMENT_TYPE='plan-of-action-and-milestones' GROUP BY 1,2
  UNION ALL
  SELECT 'SECURITY_ASSESSMENT_PLAN', TRIM(SOURCE_RECORD_ID::STRING), COUNT(*)
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_PLAN_ELEMENT
  WHERE SOURCE_SYSTEM_NAME='ARCHER' AND SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
    AND ELEMENT_TYPE='assessment-plan' GROUP BY 1,2
),
models AS (
  SELECT COLUMN1 MODEL FROM VALUES ('SSP'),('ASSESSMENT_RESULTS'),('POAM'),('SECURITY_ASSESSMENT_PLAN')
)
SELECT m.MODEL, s.CONTENT_ID,
       CASE WHEN r.CONTENT_ID IS NULL THEN 'MISSING_ROOT'
            WHEN r.N<>1 THEN 'DUPLICATE_ROOT'
       END DEFECT,
       COALESCE(r.N,0) ROOT_COUNT
FROM src s CROSS JOIN models m
LEFT JOIN roots r ON r.MODEL=m.MODEL AND r.CONTENT_ID=s.CONTENT_ID
WHERE r.CONTENT_ID IS NULL OR r.N<>1
UNION ALL
SELECT r.MODEL, r.CONTENT_ID, 'EXTRA_ROOT', r.N
FROM roots r LEFT JOIN src s USING(CONTENT_ID)
WHERE s.CONTENT_ID IS NULL
ORDER BY MODEL, CONTENT_ID
LIMIT 500;


