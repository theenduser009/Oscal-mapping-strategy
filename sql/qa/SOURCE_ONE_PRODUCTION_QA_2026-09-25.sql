-- =====================================================================
-- 08. POAM SOURCE/TARGET ITEM COUNT PARITY BY CONTENT_ID
-- Expected: zero mismatch rows.
-- =====================================================================
WITH source_counts AS (
  SELECT
    TRIM(s.CONTENT_ID::STRING) CONTENT_ID,
    COUNT(f.VALUE) N
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW s,
       LATERAL FLATTEN(INPUT => s.CURATED_JSON:POAMS, OUTER => TRUE) f
  WHERE f.VALUE IS NOT NULL
  GROUP BY 1
),
target_counts AS (
  SELECT TRIM(SOURCE_RECORD_ID::STRING) CONTENT_ID, COUNT(*) N
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_POAM_ELEMENT
  WHERE SOURCE_SYSTEM_NAME='ARCHER'
    AND SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
    AND ELEMENT_TYPE='poam-items'
  GROUP BY 1
)
SELECT
  COALESCE(s.CONTENT_ID,t.CONTENT_ID) CONTENT_ID,
  COALESCE(s.N,0) SOURCE_POAM_ITEMS,
  COALESCE(t.N,0) TARGET_POAM_ITEMS
FROM source_counts s
FULL OUTER JOIN target_counts t USING(CONTENT_ID)
WHERE COALESCE(s.N,0)<>COALESCE(t.N,0)
ORDER BY CONTENT_ID
LIMIT 500;


-- =====================================================================
-- 09. DIRECT FIELD VALUE PARITY ACROSS ALL SOURCE RECORDS
-- These are intentionally simple direct/native mappings where exact equality
-- is expected after the approved transform.
-- Expected MISMATCH_COUNT = 0 for every row.
-- =====================================================================
WITH
src AS (
  SELECT TRIM(CONTENT_ID::STRING) CONTENT_ID, CURATED_JSON
  FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW
),
meta AS (
  SELECT TRIM(SOURCE_RECORD_ID::STRING) CONTENT_ID, METADATA_JSON
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT
  WHERE SOURCE_SYSTEM_NAME='ARCHER' AND SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
    AND ELEMENT_TYPE='metadata'
),
sc AS (
  SELECT TRIM(SOURCE_RECORD_ID::STRING) CONTENT_ID, METADATA_JSON
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT
  WHERE SOURCE_SYSTEM_NAME='ARCHER' AND SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
    AND ELEMENT_TYPE='system-characteristics'
),
boundary AS (
  SELECT TRIM(SOURCE_RECORD_ID::STRING) CONTENT_ID, METADATA_JSON
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT
  WHERE SOURCE_SYSTEM_NAME='ARCHER' AND SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
    AND ELEMENT_TYPE='authorization-boundary'
),
checks AS (
  SELECT 'AUTHORIZATION_PACKAGE_NAME -> metadata.title' CHECK_NAME,
         COUNT_IF(NOT EQUAL_NULL(s.CURATED_JSON:AUTHORIZATION_PACKAGE_NAME::STRING,
                                 m.METADATA_JSON:title::STRING)) MISMATCH_COUNT
  FROM src s JOIN meta m USING(CONTENT_ID)
  UNION ALL
  SELECT 'AUTHORIZATION_PACKAGE_NAME -> system-name',
         COUNT_IF(NOT EQUAL_NULL(s.CURATED_JSON:AUTHORIZATION_PACKAGE_NAME::STRING,
                                 c.METADATA_JSON:"system-name"::STRING))
  FROM src s JOIN sc c USING(CONTENT_ID)
  UNION ALL
  SELECT 'ACRONYM -> system-name-short',
         COUNT_IF(NOT EQUAL_NULL(s.CURATED_JSON:ACRONYM::STRING,
                                 c.METADATA_JSON:"system-name-short"::STRING))
  FROM src s JOIN sc c USING(CONTENT_ID)
  UNION ALL
  SELECT 'MISSION_PURPOSE -> description',
         COUNT_IF(NOT EQUAL_NULL(s.CURATED_JSON:MISSION_PURPOSE::STRING,
                                 c.METADATA_JSON:description::STRING))
  FROM src s JOIN sc c USING(CONTENT_ID)
  UNION ALL
  SELECT 'AUTHORIZATION_BOUNDARY_DESCRIPTION -> authorization-boundary.description',
         COUNT_IF(NOT EQUAL_NULL(s.CURATED_JSON:AUTHORIZATION_BOUNDARY_DESCRIPTION::STRING,
                                 b.METADATA_JSON:description::STRING))
  FROM src s JOIN boundary b USING(CONTENT_ID)
)
SELECT CHECK_NAME, MISMATCH_COUNT, IFF(MISMATCH_COUNT=0,'PASS','FAIL') STATUS
FROM checks
ORDER BY CHECK_NAME;


