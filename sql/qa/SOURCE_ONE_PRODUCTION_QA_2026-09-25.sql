-- =====================================================================
-- 01. CURRENT RELEASE MODEL COUNTS + GRAPH CARDINALITY
-- In this graph design every non-root node has exactly one incoming edge,
-- therefore SOURCE-ONE edge count must equal node count minus root count.
--
-- Current accepted release baseline:
-- SSP:                   546799 nodes / 543986 edges
-- ASSESSMENT_RESULTS:    109630 nodes / 106817 edges
-- POAM:                    2821 nodes /      8 edges
-- SECURITY_ASSESSMENT_PLAN:11252 nodes /   8439 edges
-- =====================================================================
WITH
ssp_d AS (
  SELECT *
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT
  WHERE SOURCE_SYSTEM_NAME='ARCHER'
    AND SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
),
ssp_f AS (
  SELECT f.*
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_SSP_DEPENDENCY f
  JOIN ssp_d s ON s.PK_OSCAL_SSP_ELEMENT_HASH=f.FK_SOURCE_ELEMENT_HASH
  JOIN ssp_d t ON t.PK_OSCAL_SSP_ELEMENT_HASH=f.FK_TARGET_ELEMENT_HASH
),
ar_d AS (
  SELECT *
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT
  WHERE SOURCE_SYSTEM_NAME='ARCHER'
    AND SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
),
ar_f AS (
  SELECT f.*
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_ASSESSMENT_RESULTS_DEPENDENCY f
  JOIN ar_d s ON s.PK_DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT_HASH=f.FK_SOURCE_ELEMENT_HASH
  JOIN ar_d t ON t.PK_DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT_HASH=f.FK_TARGET_ELEMENT_HASH
),
poam_d AS (
  SELECT *
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_POAM_ELEMENT
  WHERE SOURCE_SYSTEM_NAME='ARCHER'
    AND SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
),
poam_f AS (
  SELECT f.*
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_POAM_DEPENDENCY f
  JOIN poam_d s ON s.PK_DIM_OSCAL_POAM_ELEMENT_HASH=f.FK_SOURCE_ELEMENT_HASH
  JOIN poam_d t ON t.PK_DIM_OSCAL_POAM_ELEMENT_HASH=f.FK_TARGET_ELEMENT_HASH
),
sap_d AS (
  SELECT *
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_PLAN_ELEMENT
  WHERE SOURCE_SYSTEM_NAME='ARCHER'
    AND SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
),
sap_f AS (
  SELECT f.*
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_ASSESSMENT_PLAN_DEPENDENCY f
  JOIN sap_d s ON s.PK_DIM_OSCAL_ASSESSMENT_PLAN_ELEMENT_HASH=f.FK_SOURCE_ELEMENT_HASH
