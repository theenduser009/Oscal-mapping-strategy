-- =====================================================================
-- 04. FACT / RELATIONSHIP INTEGRITY
-- Expected every DEFECT_COUNT = 0.
-- Includes:
--   duplicate fact PK
--   null FK
--   orphan source/target FK
--   self edge
--   fact UUID mismatch against DIM UUID
--   cross-record edge inside Source One
--   cross-source-namespace edge (especially important for shared AR tables)
-- =====================================================================
WITH checks AS (
  -- SSP
  SELECT 'SSP' MODEL,'DUPLICATE_FACT_PK' DEFECT,COUNT(*) DEFECT_COUNT FROM (
    SELECT PK_FACT_OSCAL_DEPENDENCY_HASH
    FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_SSP_DEPENDENCY
    GROUP BY 1 HAVING COUNT(*)>1
  )
  UNION ALL
  SELECT 'SSP','NULL_FK',
    COUNT_IF(FK_SOURCE_ELEMENT_HASH IS NULL OR FK_TARGET_ELEMENT_HASH IS NULL)
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_SSP_DEPENDENCY
  UNION ALL
  SELECT 'SSP','ORPHAN_SOURCE_FK',COUNT(*)
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_SSP_DEPENDENCY f
  LEFT JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT d
    ON d.PK_OSCAL_SSP_ELEMENT_HASH=f.FK_SOURCE_ELEMENT_HASH
  WHERE d.PK_OSCAL_SSP_ELEMENT_HASH IS NULL
  UNION ALL
  SELECT 'SSP','ORPHAN_TARGET_FK',COUNT(*)
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_SSP_DEPENDENCY f
  LEFT JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT d
    ON d.PK_OSCAL_SSP_ELEMENT_HASH=f.FK_TARGET_ELEMENT_HASH
  WHERE d.PK_OSCAL_SSP_ELEMENT_HASH IS NULL
  UNION ALL
  SELECT 'SSP','SELF_EDGE',COUNT_IF(FK_SOURCE_ELEMENT_HASH=FK_TARGET_ELEMENT_HASH)
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_SSP_DEPENDENCY
  UNION ALL
  SELECT 'SSP','UUID_MISMATCH',COUNT(*)
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_SSP_DEPENDENCY f
  JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT s
    ON s.PK_OSCAL_SSP_ELEMENT_HASH=f.FK_SOURCE_ELEMENT_HASH
  JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT t
    ON t.PK_OSCAL_SSP_ELEMENT_HASH=f.FK_TARGET_ELEMENT_HASH
  WHERE f.SOURCE_OSCAL_UUID<>s.OSCAL_UUID OR f.TARGET_OSCAL_UUID<>t.OSCAL_UUID
  UNION ALL
