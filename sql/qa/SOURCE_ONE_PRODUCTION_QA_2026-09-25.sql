),
counts AS (
  SELECT 'SSP' MODEL, (SELECT COUNT(*) FROM ssp_d) NODES,
         (SELECT COUNT_IF(ELEMENT_TYPE='system-security-plan') FROM ssp_d) ROOTS,
         (SELECT COUNT(*) FROM ssp_f) EDGES,
         546799 BASELINE_NODES, 543986 BASELINE_EDGES
  UNION ALL
  SELECT 'ASSESSMENT_RESULTS', (SELECT COUNT(*) FROM ar_d),
         (SELECT COUNT_IF(ELEMENT_TYPE='assessment-results') FROM ar_d),
         (SELECT COUNT(*) FROM ar_f), 109630, 106817
  UNION ALL
