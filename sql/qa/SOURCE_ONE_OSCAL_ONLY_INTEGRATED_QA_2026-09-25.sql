  SELECT TRIM(s.SOURCE_RECORD_ID::STRING) SOURCE_RECORD_ID,COUNT(*) EDGE_COUNT,
         COUNT_IF(s.SOURCE_RECORD_ID<>t.SOURCE_RECORD_ID) CROSS_RECORD_EDGES
