   AND s.SOURCE_SYSTEM_NAME='ARCHER'
   AND s.SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
  JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT t
    ON t.PK_DIM_OSCAL_ASSESSMENT_RESULTS_ELEMENT_HASH=f.FK_TARGET_ELEMENT_HASH
   AND t.SOURCE_SYSTEM_NAME='ARCHER'
   AND t.SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
  GROUP BY 1
),
poam AS (
  SELECT TRIM(SOURCE_RECORD_ID::STRING) SOURCE_RECORD_ID,
         COUNT(*) NODE_COUNT,
         COUNT_IF(ELEMENT_TYPE='plan-of-action-and-milestones') ROOT_COUNT
  FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_POAM_ELEMENT
  WHERE SOURCE_SYSTEM_NAME='ARCHER'
    AND SOURCE_TABLE_NAME='ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
