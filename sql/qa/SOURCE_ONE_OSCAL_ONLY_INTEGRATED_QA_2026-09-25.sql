  SELECT SOURCE_RECORD_ID FROM ssp
  UNION SELECT SOURCE_RECORD_ID FROM ar
  UNION SELECT SOURCE_RECORD_ID FROM poam
  UNION SELECT SOURCE_RECORD_ID FROM sap
),
m AS (
  SELECT
    ids.SOURCE_RECORD_ID,
    IFF(ssp.SOURCE_RECORD_ID IS NULL,1,0) MISS_SSP,
    IFF(ar.SOURCE_RECORD_ID IS NULL,1,0) MISS_AR,
    IFF(poam.SOURCE_RECORD_ID IS NULL,1,0) MISS_POAM,
    IFF(sap.SOURCE_RECORD_ID IS NULL,1,0) MISS_SAP,
    IFF(ssp.ROOT_COUNT<>1 OR COALESCE(ssp_e.EDGE_COUNT,0)<>ssp.NODE_COUNT-1
        OR COALESCE(ssp_e.CROSS_RECORD_EDGES,0)<>0,1,0) SSP_BAD,
    IFF(ar.ROOT_COUNT<>1 OR COALESCE(ar_e.EDGE_COUNT,0)<>ar.NODE_COUNT-1
        OR COALESCE(ar_e.CROSS_RECORD_EDGES,0)<>0,1,0) AR_BAD,
    IFF(poam.ROOT_COUNT<>1 OR COALESCE(poam_e.EDGE_COUNT,0)<>poam.NODE_COUNT-1
        OR COALESCE(poam_e.CROSS_RECORD_EDGES,0)<>0,1,0) POAM_BAD,
    IFF(sap.ROOT_COUNT<>1 OR COALESCE(sap_e.EDGE_COUNT,0)<>sap.NODE_COUNT-1
        OR COALESCE(sap_e.CROSS_RECORD_EDGES,0)<>0,1,0) SAP_BAD
