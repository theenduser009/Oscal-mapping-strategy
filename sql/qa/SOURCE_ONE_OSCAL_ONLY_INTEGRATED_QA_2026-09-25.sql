  LEFT JOIN ssp_e USING(SOURCE_RECORD_ID)
  LEFT JOIN ar USING(SOURCE_RECORD_ID)
  LEFT JOIN ar_e USING(SOURCE_RECORD_ID)
  LEFT JOIN poam USING(SOURCE_RECORD_ID)
  LEFT JOIN poam_e USING(SOURCE_RECORD_ID)
  LEFT JOIN sap USING(SOURCE_RECORD_ID)
  LEFT JOIN sap_e USING(SOURCE_RECORD_ID)
)
SELECT
  COUNT(*) AS INTEGRATED_SOURCE_RECORD_IDS,
  COUNT_IF(MISS_SSP=1) AS MISSING_SSP,
  COUNT_IF(MISS_AR=1) AS MISSING_ASSESSMENT_RESULTS,
  COUNT_IF(MISS_POAM=1) AS MISSING_POAM,
  COUNT_IF(MISS_SAP=1) AS MISSING_ASSESSMENT_PLAN,
  COUNT_IF(SSP_BAD=1) AS SSP_INTEGRITY_FAILURES,
  COUNT_IF(AR_BAD=1) AS AR_INTEGRITY_FAILURES,
  COUNT_IF(POAM_BAD=1) AS POAM_INTEGRITY_FAILURES,
  COUNT_IF(SAP_BAD=1) AS SAP_INTEGRITY_FAILURES,
  IFF(
    COUNT_IF(MISS_SSP+MISS_AR+MISS_POAM+MISS_SAP+SSP_BAD+AR_BAD+POAM_BAD+SAP_BAD>0)=0,
    'PASS','FAIL'
  ) AS OVERALL_STATUS
FROM m;


